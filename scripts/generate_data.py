# --------------------------------------------------------------------------
# Weekly "plans": how many reviews, what mix, which complaint themes
# --------------------------------------------------------------------------
BASE_MIX = {"positive": 0.55, "negative": 0.15, "neutral": 0.17, "mixed": 0.10, "tricky": 0.03}
BASE_CATS = {"delivery": 0.15, "quality": 0.30, "support": 0.15, "pricing": 0.12,
             "website": 0.13, "returns": 0.10, "other": 0.05}
# During the bad period delivery and support dominate, website is secondary
BAD_CATS = {"delivery": 0.60, "support": 0.40, "website": 0.20, "quality": 0.10,
            "pricing": 0.05, "returns": 0.10, "other": 0.03}


def bad_mix(negative, positive):
    rest = 1.0 - negative - positive
    return {"positive": positive, "negative": negative, "neutral": rest * 0.6,
            "mixed": rest * 0.3, "tricky": rest * 0.1}


# ISO week number (2026) -> overrides. Weeks not listed use the normal baseline.
WEEK_PLANS = {
    19: {"n": (21, 26), "mix": bad_mix(0.35, 0.30), "cats": BAD_CATS},  # ramp-up
    20: {"n": (27, 34), "mix": bad_mix(0.55, 0.12), "cats": BAD_CATS},  # worst
    21: {"n": (27, 34), "mix": bad_mix(0.60, 0.10), "cats": BAD_CATS},  # worst
    22: {"n": (25, 32), "mix": bad_mix(0.50, 0.15), "cats": BAD_CATS},
    23: {"n": (21, 26), "mix": bad_mix(0.20, 0.42), "cats": BAD_CATS},  # recovery
    27: {"empty": True},                                                  # no reviews at all
    33: {"fixed": 4, "mix": {"negative": 1.0}, "cats": {"delivery": 0.8, "support": 0.2}},
}


def pick(rng, weights):
    """Pick a key from {key: weight} using the seeded random generator."""
    keys = list(weights)
    return rng.choices(keys, weights=[weights[k] for k in keys])[0]


def fill(rng, template):
    return template.format(item=rng.choice(ITEMS))


def negative_review(rng, cat_weights):
    """One or two complaint sentences from weighted categories (+ optional closer)."""
    primary = pick(rng, cat_weights)
    sentences = [fill(rng, rng.choice(NEGATIVE[primary]))]
    if primary != "other" and rng.random() < 0.40:
        others = {c: w for c, w in cat_weights.items() if c not in (primary, "other")}
        sentences.append(fill(rng, rng.choice(NEGATIVE[pick(rng, others)])))
    closer = rng.choice(NEGATIVE_CLOSERS)
    if closer:
        sentences.append(closer)
    return " ".join(sentences)


def make_text(rng, kind, cat_weights):
    if kind == "positive":
        text = fill(rng, rng.choice(POSITIVE))
        if rng.random() < 0.25:
            text += " " + rng.choice(["Ordered earlier this month.", "Second time buying here."])
        return text
    if kind == "negative":
        return negative_review(rng, cat_weights)
    if kind == "neutral":
        return fill(rng, rng.choice(NEUTRAL))
    if kind == "mixed":
        return fill(rng, rng.choice(MIXED))
    return rng.choice(TRICKY)  # "tricky"


def generate_reviews(seed=DEFAULT_SEED):
    """Return a list of (datetime, text, kind) sorted by time. `kind` is only for checking."""
    rng = random.Random(seed)
    reviews = []
    monday = START - timedelta(days=START.weekday())
    while monday <= END:
        iso_week = monday.isocalendar()[1]
        plan = WEEK_PLANS.get(iso_week, {})
        days = [monday + timedelta(days=i) for i in range(7)]
        days = [d for d in days if START <= d <= END]
        if not plan.get("empty") and days:
            if "fixed" in plan:
                count = plan["fixed"]
            else:
                lo, hi = plan.get("n", (17, 25))
                count = max(1, round(rng.randint(lo, hi) * len(days) / 7))
            mix = plan.get("mix", BASE_MIX)
            cats = plan.get("cats", BASE_CATS)
            day_weights = [1.0 if d.weekday() < 5 else 0.7 for d in days]
            for _ in range(count):
                day = rng.choices(days, weights=day_weights)[0]
                moment = datetime(day.year, day.month, day.day,
                                  rng.randint(7, 22), rng.randint(0, 59), rng.randint(0, 59))
                kind = pick(rng, mix)
                reviews.append((moment, make_text(rng, kind, cats), kind))
        monday += timedelta(days=7)
    reviews.sort(key=lambda r: r[0])
    return reviews


def build_database(path, seed=DEFAULT_SEED):
    """Create (or overwrite) the SQLite file at `path`. Returns the number of reviews."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        path.unlink()
    reviews = generate_reviews(seed)
    conn = sqlite3.connect(str(path))
    try:
        conn.executescript(
            """
            CREATE TABLE reviews (
                id          INTEGER PRIMARY KEY,
                review_date TEXT NOT NULL,   -- 'YYYY-MM-DD HH:MM:SS' (date part is what matters)
                review_text TEXT NOT NULL
            );
            -- Optional table: lets the pipeline label the dataset on the dashboard.
            CREATE TABLE dataset_info (key TEXT PRIMARY KEY, value TEXT);
            """
        )
        conn.executemany(
            "INSERT INTO reviews (id, review_date, review_text) VALUES (?, ?, ?)",
            [(i, moment.strftime("%Y-%m-%d %H:%M:%S"), text)
             for i, (moment, text, _kind) in enumerate(reviews, start=1)],
        )
        conn.executemany(
            "INSERT INTO dataset_info (key, value) VALUES (?, ?)",
            [("name", DATASET_NAME), ("is_synthetic", "true"), ("notice", DATASET_NOTICE)],
        )
        conn.commit()
    finally:
        conn.close()
    return len(reviews)


def main():
    parser = argparse.ArgumentParser(description="Generate the synthetic SentimentPulse demo database.")
    root = Path(__file__).resolve().parents[1]
    parser.add_argument("--out", default=str(root / "data" / "reviews.db"), help="output .db file")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED, help="random seed (default 42)")
    args = parser.parse_args()
    n = build_database(args.out, args.seed)
    print(f"Wrote {n} synthetic reviews to {args.out}")
    print("Reminder: this is demonstration data, not real customer feedback.")


if __name__ == "__main__":
    main()
